public class Main {

    public static void main(String[] args) {

        int numero = 10;

        System.out.println("Valor inicial: " + numero);

        numero++;
        System.out.println("Depois do incremento: " + numero);

        numero++;
        System.out.println("Depois de outro incremento: " + numero);

        numero--;
        System.out.println("Depois do decremento: " + numero);

        numero--;
        System.out.println("Depois de outro decremento: " + numero);
    }
}