public class Main {

    public static void main(String[] args) {

        int resultado1 = 10 + 5 * 2;
        int resultado2 = (10 + 5) * 2;
        int resultado3 = 20 / 2 + 5;
        int resultado4 = 20 / (2 + 5);

        System.out.println("10 + 5 * 2 = " + resultado1);
        System.out.println("(10 + 5) * 2 = " + resultado2);
        System.out.println("20 / 2 + 5 = " + resultado3);
        System.out.println("20 / (2 + 5) = " + resultado4);
    }
}